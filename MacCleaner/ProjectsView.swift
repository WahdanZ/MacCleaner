import AppKit
import SwiftUI

struct ProjectsView: View {
    @Environment(ProjectsModel.self) private var m
    @Environment(ReviewCenter.self) private var review

    var body: some View {
        @Bindable var m = m
        VStack(spacing: 14) {
            // Folders + filters
            HStack(spacing: 10) {
                ScrollView(.horizontal) {
                    HStack(spacing: 6) {
                        ForEach(m.roots, id: \.self) { r in
                            HStack(spacing: 5) {
                                Image(systemName: "folder.fill").font(.system(size: 11)).foregroundStyle(Palette.accent)
                                Text(r.lastPathComponent).font(.system(size: 12, weight: .medium))
                                Button { m.roots.removeAll { $0 == r } } label: { Image(systemName: "xmark").font(.system(size: 9, weight: .bold)) }
                                    .buttonStyle(.plain).foregroundStyle(Palette.faint)
                            }
                            .padding(.horizontal, 10).padding(.vertical, 5)
                            .background(Palette.fg.opacity(0.06), in: Capsule())
                            .help(r.path)
                        }
                        Button { m.addRoot() } label: { Label("Add folder", systemImage: "plus") }.buttonStyle(.bordered)
                    }
                }
                .scrollIndicators(.never)
                .disabled(m.phase == .scanning || m.phase == .cleaning)
                Spacer()
                if m.phase != .scanning {
                    Button { m.scan() } label: { Label(m.phase == .idle ? "Scan projects" : "Rescan", systemImage: "magnifyingglass") }
                        .buttonStyle(.borderedProminent)
                        .disabled(m.roots.isEmpty || m.phase == .cleaning)
                }
            }

            if let msg = m.message { MessageBar(text: msg.text, isError: msg.isError) { m.message = nil } }

            Group {
                switch m.phase {
                case .idle:
                    EmptyState(symbol: "hammer", title: "Clean build files from your projects",
                               text: "Finds node_modules, build, .dart_tool, .gradle, Pods, target and similar folders. They come back automatically the next time you build or install packages. Your source code is never touched.")
                case .scanning, .cleaning:
                    WorkingState(symbol: m.phase == .scanning ? "hammer" : "trash",
                                 title: m.phase == .scanning ? "Scanning projects…" : "Cleaning…",
                                 detail: Scanner.tilde(URL(fileURLWithPath: m.current)))
                case .done:
                    if m.projects.isEmpty {
                        EmptyState(symbol: "checkmark.seal", title: "No build files found",
                                   text: "Add the folders where you keep your projects, then scan again.")
                    } else {
                        VStack(spacing: 0) {
                            HStack(spacing: 12) {
                                Text("\(m.visible.count) of \(m.projects.count) projects · \(ByteText.string(m.visibleBytes))")
                                    .font(.system(size: 13, weight: .semibold))
                                Spacer()
                                Picker("Untouched for", selection: $m.minIdleMonths) {
                                    Text("Any time").tag(0); Text("1+ month").tag(1); Text("3+ months").tag(3)
                                    Text("6+ months").tag(6); Text("1+ year").tag(12)
                                }
                                .fixedSize()
                                Picker("Sort", selection: $m.sort) { ForEach(ProjectsModel.Sort.allCases) { Text($0.rawValue).tag($0) } }
                                    .fixedSize()
                                Button("Select shown") { m.selectVisible() }.buttonStyle(.bordered)
                                Button("None") { m.selected = [] }.buttonStyle(.bordered).disabled(m.selected.isEmpty)
                            }
                            .padding(14)
                            Divider().opacity(0.6)
                            ScrollView {
                                LazyVStack(spacing: 4) {
                                    ForEach(Array(m.visible.enumerated()), id: \.1.id) { i, p in ProjectRow(project: p).appearIn(i) }
                                }
                                .padding(10)
                            }
                        }
                    }
                }
            }
            .animation(.easeInOut(duration: 0.25), value: m.phase)
            .frame(maxWidth: .infinity, maxHeight: .infinity)
            .panel()

            HStack {
                Text("Build files are deleted permanently: they're regenerated by your build tools, not kept in the Trash.")
                    .font(.system(size: 11)).foregroundStyle(Palette.faint)
                Spacer()
                Button { review.present(ReviewBuild.projects(m) { Task { await m.clean() } }) } label: {
                    Label(m.selected.isEmpty ? "Clean" : "Clean \(ByteText.string(m.selectedBytes))", systemImage: "hammer")
                        .contentTransition(.numericText())
                }
                .animation(.snappy, value: m.selectedBytes)
                .buttonStyle(.borderedProminent)
                .disabled(m.selected.isEmpty || m.phase != .done)
            }
        }
    }

    private var summary: String {
        let pairs = m.selectedPairs
        let byProject = Dictionary(grouping: pairs, by: { $0.1.id })
        let lines = byProject.values
            .sorted { $0.reduce(0) { $0 + $1.0.size } > $1.reduce(0) { $0 + $1.0.size } }
            .prefix(12)
            .map { group in
                "• \(group[0].1.name): " + group.map { "\($0.0.rel) \(ByteText.string($0.0.size))" }.joined(separator: ", ")
            }
        let more = byProject.count > 12 ? "\n• …and \(byProject.count - 12) more projects" : ""
        let review = pairs.filter { $0.0.review }.count
        return lines.joined(separator: "\n") + more
            + (review > 0 ? "\n\n\(review) selected item(s) are marked REVIEW (dist, venv…)." : "")
            + "\n\nDeleted permanently. Source code, .git and settings are not touched."
    }
}

private struct ProjectRow: View {
    @Environment(ProjectsModel.self) private var m
    let project: DevProject
    @State private var hover = false

    var body: some View {
        let open = m.expanded.contains(project.id)
        let mainIDs = project.artifacts.filter { !$0.review }.map(\.id)
        let selCount = project.artifacts.filter { m.selected.contains($0.id) }.count
        let allOn = !mainIDs.isEmpty && mainIDs.allSatisfy(m.selected.contains)
        VStack(alignment: .leading, spacing: 0) {
            HStack(spacing: 12) {
                Button {
                    withAnimation(.snappy) { if open { m.expanded.remove(project.id) } else { m.expanded.insert(project.id) } }
                } label: {
                    Image(systemName: "chevron.right").font(.system(size: 10, weight: .bold))
                        .rotationEffect(.degrees(open ? 90 : 0)).foregroundStyle(Palette.dim).frame(width: 14, height: 20)
                        .contentShape(Rectangle())
                }
                .buttonStyle(.plain)
                if project.isProtected {
                    Image(systemName: "lock.fill").font(.system(size: 13)).foregroundStyle(Palette.accent).frame(width: 18)
                } else {
                    Button { m.toggleProject(project) } label: {
                        CheckSquare(on: allOn, color: Palette.accent, mixed: !allOn && selCount > 0)
                    }
                    .buttonStyle(.plain)
                }
                IconTile(symbol: symbol, color: color, size: 34)
                VStack(alignment: .leading, spacing: 2) {
                    HStack(spacing: 6) {
                        Text(project.name).font(.system(size: 14, weight: .semibold)).lineLimit(1)
                        Tag(text: project.stack.uppercased(), color: color)
                    }
                    Text("\(Scanner.tilde(project.url.deletingLastPathComponent())) · \(idleText)")
                        .font(.system(size: 11)).foregroundStyle(Palette.faint).lineLimit(1).truncationMode(.middle)
                }
                Spacer()
                Text(project.artifacts.map(\.rel).prefix(3).joined(separator: ", ") + (project.artifacts.count > 3 ? "…" : ""))
                    .font(.mono(10.5)).foregroundStyle(Palette.dim).lineLimit(1).frame(maxWidth: 260, alignment: .trailing)
                Text(ByteText.string(project.total)).font(.system(size: 14, weight: .semibold)).monospacedDigit()
                    .frame(width: 84, alignment: .trailing)
                Button { NSWorkspace.shared.activateFileViewerSelecting([project.url]) } label: { Image(systemName: "magnifyingglass") }
                    .buttonStyle(.plain).foregroundStyle(Palette.dim).help("Reveal in Finder")
            }
            .padding(.horizontal, 10).padding(.vertical, 8)

            if open {
                VStack(spacing: 2) {
                    ForEach(project.artifacts) { a in
                        let ok = m.isSelectable(a, project)
                        HStack(spacing: 10) {
                            Button { m.toggle(a, project) } label: {
                                if ok { CheckSquare(on: m.selected.contains(a.id), color: Palette.accent) }
                                else { Image(systemName: "lock.fill").font(.system(size: 11)).foregroundStyle(Palette.faint).frame(width: 18) }
                            }
                            .buttonStyle(.plain).disabled(!ok)
                            Text(a.rel).font(.mono(12, .medium))
                            if a.review { ReviewTag() }
                            Text("\(a.kind) · comes back with \(a.regen)").font(.system(size: 11)).foregroundStyle(Palette.faint).lineLimit(1)
                            Spacer()
                            Text(ByteText.string(a.size)).font(.system(size: 12)).monospacedDigit().foregroundStyle(Palette.dim)
                        }
                        .padding(.horizontal, 10).padding(.vertical, 4)
                        .help(ProjectEngine.reason(a, in: project) ?? a.url.path)
                    }
                }
                .padding(.leading, 70).padding(.bottom, 8)
            }
        }
        .background(hover ? Palette.fg.opacity(0.035) : .clear, in: RoundedRectangle(cornerRadius: 12, style: .continuous))
        .onHover { hover = $0 }
    }

    private var idleText: String {
        guard let d = project.lastTouched else { return "never edited" }
        return "edited " + d.formatted(.relative(presentation: .named))
    }

    private var symbol: String {
        switch project.stack {
        case "Flutter": return "bird"
        case "Node": return "shippingbox"
        case "Android/Gradle": return "iphone.gen3"
        case "iOS", "Swift": return "swift"
        case "Rust": return "gearshape.2"
        case "Python": return "chevron.left.forwardslash.chevron.right"
        default: return "hammer"
        }
    }

    private var color: Color {
        switch project.stack {
        case "Flutter": return Color(hex: 0x1A7CFF)
        case "Node": return Color(hex: 0x22A54A)
        case "Android/Gradle": return Color(hex: 0x7DC42F)
        case "iOS", "Swift": return Color(hex: 0xF97316)
        case "Rust": return Color(hex: 0xB45309)
        case "Python": return Color(hex: 0x8B5CF6)
        default: return Color(hex: 0x8A94A6)
        }
    }
}
